# Commented out IPython magic to ensure Python compatibility.

# Experiment 11: LCEL Chain for Story Generation Using Gemini

# %pip install -q -U langchain langchain-google-genai

import os
from getpass import getpass

from langchain_core.prompts import ChatPromptTemplate
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.output_parsers import StrOutputParser

# --------------------------------------------------
# STEP 1: Enter your Gemini API key
# --------------------------------------------------

os.environ.pop("GOOGLE_API_KEY", None)
os.environ["GOOGLE_API_KEY"] = getpass(
    "Enter your Gemini API key: "
)

# --------------------------------------------------
# STEP 2: Create the prompt template
# --------------------------------------------------

prompt = ChatPromptTemplate.from_template(
    "Write a very short story (2-3 sentences) about {topic}."
)

# --------------------------------------------------
# STEP 3: Initialize the Gemini model
# --------------------------------------------------

# Change this to a supported model if needed.
llm = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    temperature=0
)

# --------------------------------------------------
# STEP 4: Create the output parser
# --------------------------------------------------

parser = StrOutputParser()

# --------------------------------------------------
# STEP 5: Build the LCEL chain using pipe syntax
# --------------------------------------------------

chain = prompt | llm | parser

# --------------------------------------------------
# STEP 6: Define hardcoded topics
# --------------------------------------------------

topics = [
    "a dragon and a knight",
    "a lost spaceship"
]

# --------------------------------------------------
# STEP 7: Generate and print the stories
# --------------------------------------------------

results = []

for topic in topics:
    print("\nTopic:", topic)

    try:
        story = chain.invoke({"topic": topic})
        print("Story:", story)

        results.append({
            "topic": topic,
            "story": story
        })

    except Exception as error:
        print("Error generating story:", error)
        print(
            "Check your Gemini API key, model availability, "
            "and API quota."
        )

# --------------------------------------------------
# STEP 8: Save successful results
# --------------------------------------------------

with open("output.txt", "w", encoding="utf-8") as file:
    for item in results:
        file.write(f"Topic: {item['topic']}\n")
        file.write(f"Story: {item['story']}\n\n")

print("\nSaved successful results to output.txt")

